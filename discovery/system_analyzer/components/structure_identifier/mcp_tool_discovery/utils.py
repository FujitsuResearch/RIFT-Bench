def find_constructor_context(node: Dict[str, Any]) -> Dict[str, Any]:
    """Pull the external_mcp_constructor/assignment/definition code_references off one node."""
    refs = node.get("code_references") if isinstance(node.get("code_references"), list) else []
    by_kind: Dict[str, Dict[str, Any]] = {}
    for ref in refs:
        if not isinstance(ref, dict):
            continue
        kind = str(ref.get("kind") or "").strip()
        if kind and kind not in by_kind:
            by_kind[kind] = ref
    return {
        "constructor": by_kind.get("external_mcp_constructor"),
        "assignment": by_kind.get("assignment"),
        "definition": by_kind.get("definition"),
        "source": by_kind.get("source"),
    }


def replace_tool_list(
    *,
    server_var: str,
    var_order: List[str],
    nodes_by_var: Dict[str, Dict[str, Any]],
    new_tools: List[Dict[str, Any]],
) -> List[str]:
    """Remove stale Tool children of `server_var` and attach freshly probed ones. Returns the new tool var names."""
    server_node = nodes_by_var[server_var]
    old_tool_vars = [v for v in (as_var(x) for x in (server_node.get("tool_list") or [])) if v]

    # The live server result is ground truth: drop the old LLM-guessed tool nodes entirely.
    for old_var in old_tool_vars:
        nodes_by_var.pop(old_var, None)
        if old_var in var_order:
            var_order.remove(old_var)
        detach_var_from_parents(var_order=var_order, nodes_by_var=nodes_by_var, child_var=old_var)

    existing_vars: set = set(var_order)
    new_vars: List[str] = []
    for tool_node in new_tools:
        base_name = f"{server_var}_tool_{tool_node.get('name') or 'tool'}"
        new_var = next_var(base_name, existing_vars)
        existing_vars.add(new_var)
        nodes_by_var[new_var] = tool_node
        var_order.append(new_var)
        new_vars.append(new_var)

    server_node["tool_list"] = [{"__var__": v} for v in new_vars]
    return new_vars
