def build_probe_script(resolver_body: str) -> str:
    """Splice the LLM-authored `_resolve_connection` body into the fixed probe template.

    The model is asked for a dedented body, but LLMs are inconsistent about honoring
    indentation instructions -- `textwrap.dedent` first strips whatever common leading
    whitespace it actually returned (whether none, 4 spaces, or something else) so exactly
    one indent level is ever added here, regardless of what the model produced.
    """
    if RESOLVER_MARKER not in PROBE_TEMPLATE:
        raise RuntimeError("mcp_tool_discovery: probe template is missing its resolver marker")
    dedented = textwrap.dedent(resolver_body)
    indented = "\n".join(
        ("    " + line if line.strip() else "") for line in dedented.splitlines()
    )
    return PROBE_TEMPLATE.replace(RESOLVER_MARKER, indented)


