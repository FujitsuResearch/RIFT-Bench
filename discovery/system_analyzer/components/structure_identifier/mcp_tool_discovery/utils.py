# LLM output extraction
# ============================================================

def _strip_code_fences(text: str) -> str:
    """Remove surrounding markdown code fences when the model returns them."""
    text = (text or "").strip()
    if text.startswith("```") and text.endswith("```"):
        lines = text.splitlines()
        if len(lines) >= 2:
            text = "\n".join(lines[1:-1]).strip()
    return text


def _strip_inner_code_fences(text: str) -> str:
    """Remove leading/trailing markdown fence marker lines without touching interior indentation.

    Unlike `_strip_code_fences`, this never calls `.strip()` on the body -- that would eat the
    leading-whitespace indentation of just the first line (since `str.strip()` only trims from
    the very start/end of the whole string), desyncing it from every other line's indentation.
    """
    lines = text.split("\n")
    if lines and lines[0].strip().startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip().startswith("```"):
        lines = lines[:-1]
    return "\n".join(lines)


def extract_resolver_body(raw_response: str) -> str:
    """Extract the `<resolver>...</resolver>` tagged function body from raw model output.

    Preserves the body's interior line indentation exactly (only trims boundary blank lines
    and stray fence markers) -- `build_probe_script` is responsible for normalizing indentation
    via `textwrap.dedent`, and it can only do that correctly if every line's relative indentation
    survives extraction untouched.
    """
    # Matching `<resolver>` then `(.*?)` directly (no `\s*` immediately inside the tags) is
    # deliberate: a regex `\s*` matches across the newline *and* the first line's leading spaces,
    # stripping only that one line's indentation and desyncing it from the rest of the body.
    text = _strip_code_fences(raw_response)
    match = re.search(r"<resolver>(.*?)</resolver>", text, re.DOTALL)
    body = match.group(1) if match else text
    return _strip_inner_code_fences(body).strip("\n")


def parse_probe_output(stdout: str) -> Dict[str, Any]:
    """Parse the last non-empty stdout line as the probe script's final JSON status object."""
    lines = [ln for ln in (stdout or "").splitlines() if ln.strip()]
    for line in reversed(lines):
        try:
            obj = json.loads(line)
        except Exception:
            continue
        if isinstance(obj, dict) and "status" in obj:
            return obj
    return {
        "status": "error",
        "error": "probe script produced no parsable JSON status line",
        "error_type": "UnparsableOutput",
    }


