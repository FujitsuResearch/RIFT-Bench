# JSON-Schema -> NodeSpec InputPort/OutputPort mapping
# ============================================================

JSON_SCHEMA_TYPE_TO_DTYPE = {
    "string": "string",
    "integer": "integer",
    "number": "number",
    "boolean": "boolean",
    "object": "object",
    "null": "any",
}


def _dtype_for_schema(schema: Any) -> str:
    """Map one JSON-Schema property definition to a NodeSpec dtype string."""
    if not isinstance(schema, dict):
        return "any"
    raw_type = schema.get("type")
    if isinstance(raw_type, list):
        raw_type = next((t for t in raw_type if t != "null"), raw_type[0] if raw_type else None)
    t = str(raw_type or "").strip().lower()
    fmt = str(schema.get("format") or "").strip().lower()
    if t == "string" and fmt == "date-time":
        return "datetime"
    if t == "array":
        items = schema.get("items")
        item_dtype = _dtype_for_schema(items) if isinstance(items, dict) else "any"
        return f"{item_dtype}[]"
    return JSON_SCHEMA_TYPE_TO_DTYPE.get(t, "any")


def input_ports_from_schema(schema: Any) -> List[Dict[str, Any]]:
    """Flatten a tool's inputSchema JSON Schema into a list of NodeSpec InputPort dicts."""
    if not isinstance(schema, dict) or not isinstance(schema.get("properties"), dict):
        return []
    required = schema.get("required") if isinstance(schema.get("required"), list) else []
    ports: List[Dict[str, Any]] = []
    for name, prop_schema in schema["properties"].items():
        if not isinstance(prop_schema, dict):
            prop_schema = {}
        ports.append(
            {
                "name": str(name),
                "dtype": _dtype_for_schema(prop_schema),
                "description": prop_schema.get("description"),
                "required": name in required,
                "default": prop_schema.get("default"),
            }
        )
    return ports


def output_ports_from_schema(schema: Any) -> Tuple[List[Dict[str, Any]], bool]:
    """Flatten a tool's outputSchema (if any) into OutputPort dicts; else a single generic placeholder."""
    if not isinstance(schema, dict) or not isinstance(schema.get("properties"), dict):
        return [{"name": "result", "dtype": "any", "output_kind": "data"}], False
    ports: List[Dict[str, Any]] = []
    for name, prop_schema in schema["properties"].items():
        if not isinstance(prop_schema, dict):
            prop_schema = {}
        ports.append(
            {
                "name": str(name),
                "dtype": _dtype_for_schema(prop_schema),
                "description": prop_schema.get("description"),
                "output_kind": "data",
            }
        )
    return (ports or [{"name": "result", "dtype": "any", "output_kind": "data"}]), True


