def load_project_root(out_dir: Path) -> Optional[str]:
    """Load the target project root recorded by the discovery stage, if present."""
    root_record_path = out_dir / "root_record.json"
    if not root_record_path.exists():
        return None
    try:
        payload = json.loads(root_record_path.read_text(encoding="utf-8"))
    except Exception:
        return None
    project_root = payload.get("project_root")
    if not isinstance(project_root, str) or not project_root.strip():
        return None
    return project_root.rstrip("/")


def command_runner(command_template: str) -> str:
    """Pick the target interpreter from a command template's first token (same logic as trace_extraction._command_runner)."""
    parts = shlex.split(command_template) if command_template else []
    runner = parts[0] if parts else "python"
    if runner in {"python", "python3"}:
        return runner
    runner_path = Path(runner)
    if runner_path.exists():
        return str(runner_path)
    return sys.executable


def run_probe_script_in_target_env(
    script_text: str,
    *,
    project_root: Path,
    command_template: str,
    env_file: Path,
    script_path: Path,
    timeout_sec: int = 45,
) -> Tuple[int, str, str]:
    """Write and execute a generated MCP-probe script inside the target repo's own environment."""
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(script_text, encoding="utf-8")

    runner = command_runner(command_template)
    bash_cmd = (
        f"if [ -f {shlex.quote(str(env_file))} ]; then set -a; . {shlex.quote(str(env_file))}; set +a; fi; "
        f"{shlex.quote(runner)} {shlex.quote(str(script_path))}"
    )

    proc = subprocess.Popen(
        ["bash", "-lc", bash_cmd],
        cwd=str(project_root),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        start_new_session=True,
    )
    try:
        stdout, stderr = proc.communicate(timeout=timeout_sec)
        return proc.returncode, stdout, stderr
    except subprocess.TimeoutExpired:
        # Kill the whole process group, not just the top-level shell, so a stdio-spawned
        # grandchild MCP server process can't be orphaned by the timeout.
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
        except Exception:
            pass
        try:
            stdout, stderr = proc.communicate(timeout=5)
        except Exception:
            stdout, stderr = "", ""
        return -1, stdout, (stderr or "") + "\n[mcp_tool_discovery] probe script timed out and was killed."


